// Writes src/fonts.generated.ts with the fonts as base64, so render tabs never
// fetch them (fetching inside parallel render tabs can hang). Run by render.mjs.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

export function embedFonts() {
  const dir = path.join(root, "public/fonts");
  const entries = fs.readdirSync(dir).filter((f) => f.endsWith(".ttf")).sort()
    .map((f) => `  ${JSON.stringify(f)}: ${JSON.stringify(fs.readFileSync(path.join(dir, f)).toString("base64"))},`);
  fs.writeFileSync(path.join(root, "src/fonts.generated.ts"), `// Generated by scripts/embed-fonts.mjs. Do not edit.\nexport const FONT_DATA: Record<string, string> = {\n${entries.join("\n")}\n};\n`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) embedFonts();
